import { chromium } from "playwright";
const OUT = process.argv[2];
const browser = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium", args: ["--no-sandbox"] });
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, isMobile: true, hasTouch: true });
const page = await ctx.newPage();
const errors = [];
page.on("pageerror", (e) => errors.push("pageerror: " + e.message));
page.on("console", (m) => { if (m.type() === "error") errors.push("console: " + m.text()); });
const shot = (n) => page.screenshot({ path: `${OUT}/${n}.png` });
const wait = (ms) => page.waitForTimeout(ms);
await page.goto("http://localhost:3100/");
await page.waitForSelector(".onboard");
await page.fill("input", "Adrien");
await page.click("button:has-text('Continuer'), button:has-text('Commencer'), button[type=submit]").catch(async()=>{ await page.keyboard.press("Enter"); });
await wait(1500);
await shot("o1-pack");
const pack = page.locator(".packstage, .pack").first();
await pack.click({ force: true });
await wait(500); await shot("o2-charge");
await wait(600); await shot("o3-tear");
await wait(400); await shot("o4-burst");
await wait(1800); await shot("o5-cards");
await page.mouse.move(195, 420); await page.mouse.down(); await wait(500); await shot("o6-hold");
await page.mouse.up(); await wait(300);
await page.mouse.click(195, 420); await wait(250); await shot("o7-flipping"); await wait(1500); await shot("o8-revealed");
await page.mouse.click(380, 420); await wait(800); await shot("o9-next");
console.log("errors:", errors);
await browser.close();
